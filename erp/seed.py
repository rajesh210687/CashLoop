def generate(seed: int) -> dict:
    rng = random.Random(seed)  # own generator, so nothing else can disturb the sequence
    fake = Faker("en_IN")
    fake.seed_instance(seed)

    reference = read_reference()
    customers, aliases = generate_customers(rng, fake, reference)
    items = generate_items(rng, reference)
    price_lists = generate_price_lists(rng, customers, items, reference)
    orders, order_lines = generate_orders(rng, customers)
    return {
        "customers": customers, "aliases": aliases, "items": items,
        "price_lists": price_lists, "orders": orders, "order_lines": order_lines,
    }


def print_summary(data: dict) -> None:
    print(f"customers         {len(data['customers']):>6}")
    print(f"customer_aliases  {len(data['aliases']):>6}")
    print(f"items             {len(data['items']):>6}")
    print(f"price_lists       {len(data['price_lists']):>6}")
    print(f"orders            {len(data['orders']):>6}")
    print(f"order_lines       {len(data['order_lines']):>6}")

    print("\nOrder status mix:")
    for status, count in Counter(row[5] for row in data["orders"]).most_common():
        print(f"  {status:<18}{count:>5}")

    n_ref = sum(c["is_reference"] for c in data["customers"])
    print(f"\nReference data loaded as-is: {n_ref} customers, "
          f"{sum(i['is_reference'] for i in data['items'])} SKUs, "
          f"{sum(1 for c in data['customers'] if c['is_reference'] for _ in c['catalog'])} prices")
    example = next(c for c in data["customers"] if c["customer_code"] == "C003")
    print(f"Example customer: {example['customer_code']} {example['legal_name']} "
          f"({example['city']}, GSTIN {example['gstin']})")
    for cid, alias in data["aliases"]:
        if cid == example["id"]:
            print(f"  alias: {alias}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Seed CashLoop's mock ERP.")
    parser.add_argument("--seed", type=int, default=42, help="random seed (default 42)")
    parser.add_argument("--dry-run", action="store_true", help="generate only; don't touch the database")
    args = parser.parse_args()

    data = generate(args.seed)

    if not args.dry_run:
        load_dotenv(REPO_ROOT / ".env")
        database_url = os.environ.get("DATABASE_URL")
        if not database_url:
            sys.exit("DATABASE_URL is not set. Copy .env.example to .env and fill it in.")
        load(database_url, data)
        print(f"Seeded CashLoop ERP (seed={args.seed}).\n")
    else:
        print(f"Dry run (seed={args.seed}), nothing written.\n")

    print_summary(data)


if __name__ == "__main__":
    main()
