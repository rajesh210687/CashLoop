def copy_rows(cur, table: str, columns: tuple[str, ...], rows) -> None:
    """Bulk-load with COPY, much faster than one INSERT per row."""
    with cur.copy(f"COPY {table} ({', '.join(columns)}) FROM STDIN") as copy:
        for row in rows:
            copy.write_row(row)


def load(database_url: str, data: dict) -> None:
    customer_cols = ("id", "customer_code", "legal_name", "gstin", "city", "state",
                     "payment_terms_days", "credit_limit", "is_active", "currency", "tier")
    item_cols = ("id", "sku", "description", "category", "uom", "base_price", "gst_rate", "is_active")

    # The `with` block commits on success and rolls back on any error,
    # so you never end up with a half-seeded database.
    with psycopg.connect(database_url) as conn, conn.cursor() as cur:
        cur.execute(SCHEMA_SQL)
        copy_rows(cur, "customers", customer_cols,
                  ([c[col] for col in customer_cols] for c in data["customers"]))
        copy_rows(cur, "customer_aliases", ("customer_id", "alias"), data["aliases"])
        copy_rows(cur, "items", item_cols,
                  ([item[col] for col in item_cols] for item in data["items"]))
        copy_rows(cur, "price_lists", ("customer_id", "item_id", "unit_price", "valid_from", "currency"),
                  data["price_lists"])
        copy_rows(cur, "orders",
                  ("id", "order_number", "customer_id", "po_number", "order_date", "status", "currency"),
                  data["orders"])
        copy_rows(cur, "order_lines",
                  ("id", "order_id", "line_no", "item_id", "quantity", "unit_price"),
                  data["order_lines"])

        # We inserted explicit ids, so move each id sequence past the max.
        # Otherwise CashLoop's first real INSERT would collide with id 1.
        for table in ("customers", "customer_aliases", "items", "orders", "order_lines"):
            cur.execute(
                f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), "
                f"(SELECT max(id) FROM {table}))"
            )


