def generate_items(rng: random.Random, reference: dict):
    """Reference SKUs first (ids 1..n, as given), then the generated catalogue."""
    items = []
    for row in reference["items"]:
        prefix = row["sku"].split("-")[0]
        items.append({
            "id": len(items) + 1,
            "sku": row["sku"],
            "description": row["description"],
            "category": REFERENCE_CATEGORY[prefix],
            "uom": row["unit"],
            "base_price": Decimal(row["base_price_inr"]).quantize(Decimal("0.01")),
            "gst_rate": Decimal("18.00"),
            "is_active": True,
            "is_reference": True,
        })

    by_category: dict[str, list] = {}
    for row in item_templates():
        by_category.setdefault(row[0], []).append(row)

    for category, quota in ITEM_QUOTAS.items():
        pool = by_category[category]
        if len(pool) < quota:
            raise ValueError(f"{category}: only {len(pool)} templates for a quota of {quota}")
        chosen = sorted(rng.sample(pool, quota), key=lambda row: row[1])
        for n, (_, description, uom, low, high) in enumerate(chosen, start=1):
            items.append({
                "id": len(items) + 1,
                "sku": f"{SKU_PREFIX[category]}-{n:05d}",
                "description": description,
                "category": category,
                "uom": uom,
                "base_price": money(rng.uniform(low, high)),
                "gst_rate": Decimal("18.00"),  # illustrative; real rates vary by HSN code
                "is_active": rng.random() > 0.04,  # ~4% discontinued SKUs
                "is_reference": False,
            })

    for key in ("sku", "description"):
        values = [i[key] for i in items]
        if len(values) != len(set(values)):
            dupes = sorted(v for v in set(values) if values.count(v) > 1)
            raise ValueError(f"Generated items collide with reference items on {key}: {dupes[:5]}")
    return items


