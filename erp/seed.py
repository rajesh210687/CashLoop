SCHEMA_SQL = """
DROP VIEW  IF EXISTS order_totals;
DROP TABLE IF EXISTS order_lines, orders, price_lists, items,
                     customer_aliases, customers CASCADE;

CREATE TABLE customers (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code      TEXT NOT NULL UNIQUE,
    legal_name         TEXT NOT NULL UNIQUE,
    gstin              TEXT NOT NULL UNIQUE,
    city               TEXT NOT NULL,
    state              TEXT NOT NULL,
    payment_terms_days INT  NOT NULL,
    credit_limit       NUMERIC(14, 2) NOT NULL,
    is_active          BOOLEAN NOT NULL DEFAULT TRUE
);

-- Known spellings of each customer, as they appear on POs and emails.
CREATE TABLE customer_aliases (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    alias       TEXT NOT NULL,
    UNIQUE (customer_id, alias)
);
CREATE INDEX customer_aliases_lower_idx ON customer_aliases (lower(alias));

CREATE TABLE items (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL UNIQUE,
    category    TEXT NOT NULL,
    uom         TEXT NOT NULL,
    base_price  NUMERIC(12, 2) NOT NULL CHECK (base_price > 0),
    gst_rate    NUMERIC(5, 2)  NOT NULL,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE
);

-- Contracted price per customer per SKU.
CREATE TABLE price_lists (
    customer_id BIGINT NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    item_id     BIGINT NOT NULL REFERENCES items (id) ON DELETE CASCADE,
    unit_price  NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    valid_from  DATE NOT NULL,
    PRIMARY KEY (customer_id, item_id)
);

CREATE TABLE orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT NOT NULL UNIQUE,
    customer_id  BIGINT NOT NULL REFERENCES customers (id),
    po_number    TEXT NOT NULL,
    order_date   DATE NOT NULL,
    status       TEXT NOT NULL CHECK (status IN ('draft', 'confirmed', 'partially_shipped',
                                                 'shipped', 'invoiced', 'paid', 'cancelled')),
    currency     TEXT NOT NULL DEFAULT 'INR',
    UNIQUE (customer_id, po_number)   -- the duplicate-PO check relies on this
);
CREATE INDEX orders_status_idx ON orders (status);

CREATE TABLE order_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    line_no     INT NOT NULL,
    item_id     BIGINT NOT NULL REFERENCES items (id),
    quantity    NUMERIC(12, 3) NOT NULL CHECK (quantity > 0),
    unit_price  NUMERIC(12, 2) NOT NULL,
    line_amount NUMERIC(14, 2) GENERATED ALWAYS AS (round(quantity * unit_price, 2)) STORED,
    UNIQUE (order_id, line_no)
);

CREATE VIEW order_totals AS
SELECT o.id AS order_id, o.order_number, o.customer_id, o.status,
       count(*)                                          AS line_count,
       sum(l.line_amount)                                AS subtotal,
       sum(round(l.line_amount * i.gst_rate / 100, 2))   AS gst_amount,
       sum(l.line_amount + round(l.line_amount * i.gst_rate / 100, 2)) AS grand_total
FROM orders o
JOIN order_lines l ON l.order_id = o.id
JOIN items i       ON i.id = l.item_id
GROUP BY o.id;
"""

