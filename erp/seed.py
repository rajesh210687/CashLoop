def join_name(*parts: str) -> str:
    return " ".join(p for p in parts if p)


def phrase_forms(phrase: str) -> list[str]:
    """Every spelling of a phrase, abbreviating each word independently."""
    per_word = [[w, *WORD_ABBREVIATIONS.get(w, [])] for w in phrase.split()]
    return [" ".join(combo) for combo in itertools.product(*per_word)]


def split_legal_suffix(name: str) -> tuple[str, str]:
    """'Shree Ganesh Engineering Pvt Ltd' -> ('Shree Ganesh Engineering', 'Private Limited')."""
    for written in sorted(SUFFIX_CANON, key=len, reverse=True):
        if name.endswith(" " + written):
            return name[: -len(written) - 1], SUFFIX_CANON[written]
    return name, ""


def make_aliases(legal_name: str, rng) -> list[str]:
    """Up to 5 realistic spellings of a customer name, as buyers actually write them."""
    body, suffix = split_legal_suffix(legal_name)
    candidates = [
        join_name(form, suf)
        for form in phrase_forms(body)
        for suf in SUFFIX_VARIANTS[suffix]
    ]
    rng.shuffle(candidates)
    wanted = rng.randint(2, 5)
    aliases: list[str] = []
    for name in candidates:
        roll = rng.random()
        if roll < 0.15:
            name = name.upper()
        elif roll < 0.30:
            name = f"M/s {name}"
        elif roll < 0.38:
            name = f"M/S. {name.upper()}"
        if name != legal_name and name not in aliases:
            aliases.append(name)
        if len(aliases) == wanted:
            break
    return aliases


def make_gstin(state_code: str, fake: Faker, rng: random.Random) -> str:
    # Right shape (state code + PAN-like block + entity no. + 'Z' + check char),
    # but the check character is random, so these will NOT pass a real checksum.
    pan = fake.bothify("?????####?", letters=string.ascii_uppercase)
    check = rng.choice(string.digits + string.ascii_uppercase)
    return f"{state_code}{pan}{rng.choice('123')}Z{check}"


