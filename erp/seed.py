def generate_price_lists(rng: random.Random, customers, items):
    """Each customer gets a contract for 50-150 SKUs at a customer-level discount.

    Discontinued SKUs can still appear, so a PO for one is a realistic exception.
    SKUs missing from a customer's list are another exception ("no contract price").
    """
    rows = []
    for c in customers:
        discount = rng.choice((0, 0.02, 0.05, 0.08, 0.10, 0.12, 0.15))
        chosen = sorted(rng.sample(items, rng.randint(50, 150)), key=lambda i: i["id"])
        c["catalog"] = []
        for item in chosen:
            price = money(float(item["base_price"]) * (1 - discount) * rng.uniform(0.97, 1.03))
            valid_from = AS_OF - timedelta(days=rng.randint(30, 540))
            rows.append((c["id"], item["id"], price, valid_from))
            c["catalog"].append((item, price))
    return rows


