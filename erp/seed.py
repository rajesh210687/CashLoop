def generate_customers(rng: random.Random, fake: Faker, reference: dict):
    """Reference customers first (ids 1..n, codes as given), then generated ones."""
    customers, alias_rows = [], []
    used_names, used_gstins, used_codes = set(), set(), set()
    reserved = reserved_po_numbers()

    def add(code, legal_name, gstin, city, state, terms, currency, tier, is_reference):
        cid = len(customers) + 1
        used_codes.add(code)
        used_names.add(legal_name)
        if gstin:
            used_gstins.add(gstin)
        customers.append({
            "id": cid,
            "customer_code": code,
            "legal_name": legal_name,
            "gstin": gstin or None,
            "city": city,
            "state": state,
            "payment_terms_days": terms,
            "credit_limit": Decimal(rng.choice((5, 10, 25, 50, 100, 200)) * 100_000),
            "is_active": True if is_reference else rng.random() > 0.04,
            "currency": currency,
            "tier": tier,
            # Internal fields used to generate orders; not stored in the database.
            "is_reference": is_reference,
            "po_style": rng.choice(PO_STYLES),
            "po_prefix": "".join(ch for ch in legal_name.split()[0].upper() if ch.isalpha())[:4],
            "po_seq": rng.randint(100, 900),
            "po_numbers": set(reserved.get(code, ())),
        })
        for alias in make_aliases(legal_name, rng):
            alias_rows.append((cid, alias))

    for row in reference["customers"]:
        add(row["customer_id"], row["name"], row["gstin"], row["city"], row["state"],
            int(row["payment_terms"].split()[-1]),  # "Net 45" -> 45
            row["currency"], row["tier"], True)

    code_numbers = itertools.count(1)

    def next_code() -> str:
        while True:
            code = f"C{next(code_numbers):03d}"
            if code not in used_codes:
                return code

    while len(customers) < N_CUSTOMERS:
        stem = rng.choice(NAME_STEMS) if rng.random() < 0.7 else fake.last_name()
        industry = rng.choice(INDUSTRIES)
        suffix = weighted_choice(rng, LEGAL_SUFFIXES)
        state, state_code, cities = rng.choice(STATES)
        city = rng.choice(cities)

        legal_name = join_name(stem, industry, suffix)
        if legal_name in used_names:
            continue
        gstin = make_gstin(state_code, fake, rng)
        if gstin in used_gstins:
            continue
        add(next_code(), legal_name, gstin, city, state,
            weighted_choice(rng, [(15, 10), (30, 40), (45, 25), (60, 20), (90, 5)]),
            "INR", rng.choice(TIERS), False)

    return customers, alias_rows


