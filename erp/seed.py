def join_name(*parts: str) -> str:
    return " ".join(p for p in parts if p)


def phrase_forms(phrase: str) -> list[str]:
    """Every spelling of a phrase, abbreviating each word independently."""
    per_word = [[w, *WORD_ABBREVIATIONS.get(w, [])] for w in phrase.split()]
    return [" ".join(combo) for combo in itertools.product(*per_word)]


def make_aliases(stem, industry, suffix, legal_name, rng) -> list[str]:
    """2-5 realistic spellings of a customer name, as buyers actually write them."""
    candidates = [
        join_name(stem, ind, suf)
        for ind in phrase_forms(industry)
        for suf in SUFFIX_VARIANTS[suffix]
    ]
    rng.shuffle(candidates)
    wanted = rng.randint(2, 5)
    aliases: list[str] = []
    for name in candidates:
        roll = rng.random()
        if roll < 0.15:
            name = name.upper()
        elif roll < 0.30:
            name = f"M/s {name}"
        elif roll < 0.38:
            name = f"M/S. {name.upper()}"
        if name != legal_name and name not in aliases:
            aliases.append(name)
        if len(aliases) == wanted:
            break
    return aliases


def make_gstin(state_code: str, fake: Faker, rng: random.Random) -> str:
    # Right shape (state code + PAN-like block + entity no. + 'Z' + check char),
    # but the check character is random, so these will NOT pass a real checksum.
    pan = fake.bothify("?????####?", letters=string.ascii_uppercase)
    check = rng.choice(string.digits + string.ascii_uppercase)
    return f"{state_code}{pan}{rng.choice('123')}Z{check}"


def generate_customers(rng: random.Random, fake: Faker):
    customers, alias_rows = [], []
    used_names, used_gstins = set(), set()

    while len(customers) < N_CUSTOMERS:
        idx = len(customers)
        if idx < len(FIXED_CUSTOMERS):
            stem, industry, suffix, city, fixed_aliases = FIXED_CUSTOMERS[idx]
            state, state_code = CITY_TO_STATE[city]
        else:
            stem = rng.choice(NAME_STEMS) if rng.random() < 0.7 else fake.last_name()
            industry = rng.choice(INDUSTRIES)
            suffix = weighted_choice(rng, LEGAL_SUFFIXES)
            state, state_code, cities = rng.choice(STATES)
            city = rng.choice(cities)
            fixed_aliases = None

        legal_name = join_name(stem, industry, suffix)
        if legal_name in used_names:
            continue
        gstin = make_gstin(state_code, fake, rng)
        if gstin in used_gstins:
            continue
        used_names.add(legal_name)
        used_gstins.add(gstin)

        cid = idx + 1
        customers.append({
            "id": cid,
            "customer_code": f"C{cid:05d}",
            "legal_name": legal_name,
            "gstin": gstin,
            "city": city,
            "state": state,
            "payment_terms_days": weighted_choice(rng, [(15, 10), (30, 40), (45, 25), (60, 20), (90, 5)]),
            "credit_limit": Decimal(rng.choice((5, 10, 25, 50, 100, 200)) * 100_000),
            "is_active": idx < len(FIXED_CUSTOMERS) or rng.random() > 0.04,
            # Internal fields used to generate orders; not stored in the database.
            "po_style": rng.choice(PO_STYLES),
            "po_prefix": "".join(ch for ch in stem.upper() if ch.isalpha())[:4],
            "po_seq": rng.randint(100, 900),
            "po_numbers": set(),
        })
        for alias in fixed_aliases or make_aliases(stem, industry, suffix, legal_name, rng):
            alias_rows.append((cid, alias))

    return customers, alias_rows


