def read_reference() -> dict:
    """Load evals/extraction/reference/*.csv exactly as written."""
    if not REFERENCE_DIR.is_dir():
        sys.exit(f"Reference data not found at {REFERENCE_DIR}. "
                 "Run python evals/build_golden_set.py or restore the evals/ folder.")

    def rows(name: str) -> list[dict]:
        with open(REFERENCE_DIR / name, newline="", encoding="utf-8") as f:
            return list(csv.DictReader(f))

    return {"customers": rows("customers.csv"), "items": rows("items.csv"),
            "prices": rows("price_list.csv")}


def reserved_po_numbers() -> dict[str, set[str]]:
    """PO numbers the golden-set emails use, per customer code.

    Generated orders must not reuse them, or the duplicate-PO check would fire
    on an email that is supposed to be new.
    """
    reserved: dict[str, set[str]] = {}
    for path in sorted(GOLD_DIR.glob("*.json")) if GOLD_DIR.is_dir() else []:
        gold = json.loads(path.read_text(encoding="utf-8"))
        pos = gold.get("expected", {}).get("purchase_orders", [])
        for po, res in zip(pos, gold.get("resolution", [])):
            if po.get("po_number") and res.get("customer_id"):
                reserved.setdefault(res["customer_id"], set()).add(po["po_number"])
    return reserved


