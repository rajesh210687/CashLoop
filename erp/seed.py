def generate_price_lists(rng: random.Random, customers, items, reference):
    """Reference prices are loaded verbatim; other customers get generated contracts.

    A generated customer gets a contract for 50-150 generated SKUs at a
    customer-level discount. Discontinued SKUs can still appear, so a PO for one
    is a realistic exception. SKUs missing from a customer's list are another
    exception ("no contract price"). Reference customers get exactly their
    reference rows, nothing more.
    """
    by_code = {c["customer_code"]: c for c in customers}
    by_sku = {i["sku"]: i for i in items}
    for c in customers:
        c["catalog"] = []

    rows = []
    for r in reference["prices"]:
        c, item = by_code[r["customer_id"]], by_sku[r["sku"]]
        price = Decimal(r["unit_price"]).quantize(Decimal("0.01"))
        rows.append((c["id"], item["id"], price, REFERENCE_VALID_FROM, r["currency"]))
        c["catalog"].append((item, price))

    generated_items = [i for i in items if not i["is_reference"]]
    for c in customers:
        if c["is_reference"]:
            continue
        discount = rng.choice((0, 0.02, 0.05, 0.08, 0.10, 0.12, 0.15))
        chosen = sorted(rng.sample(generated_items, rng.randint(50, 150)), key=lambda i: i["id"])
        for item in chosen:
            price = money(float(item["base_price"]) * (1 - discount) * rng.uniform(0.97, 1.03))
            valid_from = AS_OF - timedelta(days=rng.randint(30, 540))
            rows.append((c["id"], item["id"], price, valid_from, c["currency"]))
            c["catalog"].append((item, price))
    return rows


