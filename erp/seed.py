# Older orders are further along the lifecycle. Weights follow ORDER_STATUSES order:
#                   draft conf part ship  inv  paid canc
STATUS_BY_AGE = [
    (7,            (35,  55,   7,   0,   0,   0,   3)),
    (30,           (0,   20,  25,  35,  15,   0,   5)),
    (90,           (0,    0,   0,  15,  45,  35,   5)),
    (None,         (0,    0,   0,   0,   5,  91,   4)),
]
QTY_CHOICES = {
    "PCS": (10, 25, 50, 100, 200, 250, 500, 1000),
    "MTR": (25, 50, 100, 200, 500),
    "KG": (5, 10, 20, 25, 50, 100),
    "PAIR": (10, 12, 24, 50, 100),
}
LINES_PER_ORDER = [(1, 15), (2, 20), (3, 20), (4, 15), (5, 10), (6, 8), (7, 7), (8, 5)]


def pick_status(age_days: int, rng: random.Random) -> str:
    for max_age, weights in STATUS_BY_AGE:
        if max_age is None or age_days <= max_age:
            return rng.choices(ORDER_STATUSES, weights=weights)[0]
    raise AssertionError("unreachable")


def quantity_for(uom: str, rng: random.Random) -> Decimal:
    if uom == "NOS":
        return Decimal(rng.randint(1, 40))
    return Decimal(rng.choice(QTY_CHOICES[uom]))


def make_po_number(customer, order_date: date, rng: random.Random) -> str:
    """Each customer has its own PO numbering habit, like real buyers do."""
    while True:
        customer["po_seq"] += rng.randint(1, 9)  # gaps, as in real PO books
        seq = customer["po_seq"]
        style = customer["po_style"]
        if style == "sap":
            po = f"45{rng.randint(0, 99_999_999):08d}"
        elif style == "slash":
            po = f"PO/{fiscal_year(order_date)}/{seq:05d}"
        elif style == "prefix":
            po = f"{customer['po_prefix']}-PO-{seq:04d}"
        else:
            po = str(10_000 + seq)
        if po not in customer["po_numbers"]:
            customer["po_numbers"].add(po)
            return po


def generate_orders(rng: random.Random, customers):
    # A few big customers place most orders (Pareto-shaped volume).
    weights = [rng.paretovariate(1.3) for _ in customers]
    picks = rng.choices(customers, weights=weights, k=N_ORDERS)

    dated = []
    for c in picks:
        min_age = 0 if c["is_active"] else 181  # inactive customers stopped ordering
        dated.append((AS_OF - timedelta(days=rng.randint(min_age, 540)), c))
    dated.sort(key=lambda pair: (pair[0], pair[1]["id"]))  # ids follow date order

    order_rows, line_rows = [], []
    for order_id, (order_date, c) in enumerate(dated, start=1):
        status = pick_status((AS_OF - order_date).days, rng)
        order_rows.append((
            order_id, f"SO-{order_date.year}-{order_id:06d}", c["id"],
            make_po_number(c, order_date, rng), order_date, status, "INR",
        ))
        n_lines = weighted_choice(rng, LINES_PER_ORDER)
        for line_no, (item, price) in enumerate(rng.sample(c["catalog"], n_lines), start=1):
            line_rows.append((
                len(line_rows) + 1, order_id, line_no, item["id"],
                quantity_for(item["uom"], rng), price,
            ))
    return order_rows, line_rows


